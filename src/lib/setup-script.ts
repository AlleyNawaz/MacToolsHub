export type SetupTool = {
  name: string
  slug: string
  installCommand: string
  installKind: string
}

export function buildSetupScript(tools: SetupTool[]): string {
  const steps = tools.map((tool) => {
    if (tool.installKind === "manual") {
      return `# Manual step — ${tool.name}: ${tool.installCommand.replace(/\s+/g, " ")}`
    }

    if (tool.slug === "homebrew") {
      return [
        "if ! command -v brew >/dev/null 2>&1; then",
        `  ${tool.installCommand}`,
        "fi",
        'if [[ -x /opt/homebrew/bin/brew ]]; then eval "$(/opt/homebrew/bin/brew shellenv)"; elif [[ -x /usr/local/bin/brew ]]; then eval "$(/usr/local/bin/brew shellenv)"; fi',
      ].join("\n")
    }

    return tool.installCommand
  })

  return [
    "#!/bin/zsh",
    "set -e",
    "",
    "# Generated by MacTools Hub. Review every step before running.",
    ...(steps.length ? steps : ["# Select at least one tool to add installation steps."]),
    "",
  ].join("\n")
}
